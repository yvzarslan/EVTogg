export function normalizeLanguage(language) {
  return supportedLanguages.includes(language) ? language : defaultLanguage;
}

export function getMessage(language, key) {
  const locale = normalizeLanguage(language);
  return translations[locale][key] || translations[defaultLanguage][key] || key;
}

export function getSpecificationLabel(language, key) {
  return getMessage(language, specificationKeys[key] || key);
}

export function getSegmentTranslation(language, code, fallback = "") {
  const messageKey = segmentKeys[code];
  return messageKey ? getMessage(language, messageKey) : fallback || getMessage(language, "unknown");
}

export function getBodyStyleTranslation(language, code, fallback = "") {
  const messageKey = bodyStyleKeys[code];
  return messageKey ? getMessage(language, messageKey) : fallback || getMessage(language, "unknown");
}

export function getVehicleValue(language, car, key) {
  const locale = normalizeLanguage(language);

  if (key === "segment") {
    return getSegmentTranslation(locale, car.segmentCode, car.segment);
  }

  if (key === "body_style") {
    return getBodyStyleTranslation(locale, car.bodyStyleCode, car.body_style);
  }

  const value = car[key];
  if (!value) return "";
  if (key === "accel") return value.replace(/\bsn\b/i, getMessage(locale, "seconds"));
  if (key === "cargo") {
    const unit = locale === "ru" ? "л" : locale === "zh" ? "升" : locale === "tr" ? "litre" : "L";
    return value.replace(/\blitre\b/i, unit);
  }

  return value;
}

export function getVehicleDetailRowLabel(language, label, value) {
  const normalizedLabel = label.toLowerCase().replace(/\*/g, "").trim();
  const messageKey = normalizedLabel === "charging stop"
    ? /\bkm\b/i.test(value) ? "longChargingDistance" : "longChargingDuration"
    : vehicleDetailRowKeys[normalizedLabel];

  return messageKey ? getMessage(language, messageKey) : label;
}
